// Command genbotan writes testdata/botan-diff.vec, a differential corpus of
// Whirlpool digests produced by the installed Botan command line
// (`botan hash --algo=Whirlpool`, message on standard input). Lengths 0 to 199
// come first, so every position around the 64-byte block and the 32-byte
// length field is covered; the rest are random lengths up to 2000. Contents
// come from a fixed-seed PRNG, so a rerun with the same Botan rewrites the
// same file.
//
// Usage: go run ./internal/genbotan [-n 500] [-o testdata/botan-diff.vec]
package main

import (
	"bytes"
	"encoding/hex"
	"fmt"
	"io"
	"math/rand/v2"
	"os"
	"os/exec"
	"strings"

	"github.com/spf13/cobra"
)

var osExit = os.Exit

// run asks botan for the digest of msg; it is a variable so tests can fake it.
var run = func(msg []byte) ([]byte, error) {
	cmd := exec.Command("botan", "hash", "--algo=Whirlpool")
	cmd.Stdin = bytes.NewReader(msg)
	out, err := cmd.Output()
	if err != nil {
		return nil, err
	}
	// The output is "<HEX> -".
	f := strings.Fields(string(out))
	if len(f) == 0 {
		return nil, fmt.Errorf("botan printed nothing")
	}
	return hex.DecodeString(f[0])
}

func generate(w io.Writer, n int) error {
	r := rand.New(rand.NewPCG(1, 2))
	fmt.Fprintln(w, "# Generated by internal/genbotan from the Botan command line; do not edit.")
	fmt.Fprintln(w, "[Whirlpool]")
	for i := 0; i < n; i++ {
		size := i
		if i >= 200 {
			size = r.IntN(2001)
		}
		msg := make([]byte, size)
		for j := range msg {
			msg[j] = byte(r.Uint32())
		}
		out, err := run(msg)
		if err != nil {
			return err
		}
		if len(out) != 64 {
			return fmt.Errorf("botan returned %d bytes, want 64", len(out))
		}
		fmt.Fprintf(w, "\nIn = %X\nOut = %X\n", msg, out)
	}
	return nil
}

// RootCmd builds the command.
func RootCmd() *cobra.Command {
	var n int
	var out string
	cmd := &cobra.Command{
		Use:          "genbotan",
		Short:        "write the Botan differential corpus for Whirlpool",
		SilenceUsage: true,
		Args:         cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			var buf bytes.Buffer
			if err := generate(&buf, n); err != nil {
				return err
			}
			if err := os.WriteFile(out, buf.Bytes(), 0o644); err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "wrote %d vectors to %s\n", n, out)
			return nil
		},
	}
	cmd.Flags().IntVarP(&n, "count", "n", 500, "number of vectors")
	cmd.Flags().StringVarP(&out, "output", "o", "testdata/botan-diff.vec", "output file")
	return cmd
}

func main() {
	if err := RootCmd().Execute(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		osExit(1)
	}
}
